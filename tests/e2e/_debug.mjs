import { chromium } from "playwright";
import { installSupabaseMocks, mockSession } from "/dev-server/tests/mocks/supabase.mjs";
const b = await chromium.launch({ headless: true });
const c = await b.newContext({ viewport: { width: 1280, height: 1600 } });
const p = await c.newPage();
await installSupabaseMocks(p, { session: mockSession() });
p.on("console", (m) => console.log("PAGE:", m.type(), m.text()));
p.on("pageerror", (e) => console.log("PAGEERROR:", e.message));
await p.goto("http://localhost:8080/", { waitUntil: "domcontentloaded" });
await p.waitForLoadState("networkidle").catch(()=>{});
const buttons = await p.locator('button[aria-label="Sign out"]').all();
console.log("sign-out buttons:", buttons.length);
for (const b of buttons) console.log("visible:", await b.isVisible());
await p.evaluate(() => { window.__navigatedTo = null; window.location.assign = (u) => { window.__navigatedTo = String(u); console.log("ASSIGN CALLED", u); }; });
await p.locator('button[aria-label="Sign out"]:visible').first().click();
await p.waitForTimeout(2000);
const state = await p.evaluate(() => ({ nav: window.__navigatedTo, keys: Object.keys(localStorage) }));
console.log(JSON.stringify(state));
await b.close();
